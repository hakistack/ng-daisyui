const BY_ID = new Map(DOC_PAGES.map((p) => [p.id, p]));
const BY_ROUTE = new Map(DOC_PAGES.map((p) => [p.route, p]));

export function pageById(id: string): DocPageMeta | undefined {
  return BY_ID.get(id);
}

/** Match `/datagrid/server` → the `/datagrid` page; exact routes win. */
export function pageForUrl(url: string): DocPageMeta | undefined {
  const path = url.split(/[?#]/)[0].replace(/\/+$/, '') || '/';
  if (BY_ROUTE.has(path)) return BY_ROUTE.get(path);
  const segments = path.split('/').filter(Boolean);
  for (let n = segments.length - 1; n > 0; n--) {
    const candidate = '/' + segments.slice(0, n).join('/');
    const page = BY_ROUTE.get(candidate);
    if (page) return page;
  }
  return undefined;
}
