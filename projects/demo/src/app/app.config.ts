import { ApplicationConfig, provideBrowserGlobalErrorListeners } from '@angular/core';
import { provideRouter, withComponentInputBinding, withInMemoryScrolling } from '@angular/router';
import { provideDocsPlatform } from '@shared-demos/platform/docs-platform';
import { provideToast, provideAlert, provideHkTheme, provideFormState, provideNotification, providePipes } from '@hakistack/ng-daisyui';
import { provideLucideConfig, provideLucideIcons } from '@lucide/angular';
import { USED_LUCIDE_ICONS } from './lucide-icons.generated';

import { routes } from './app.routes';

/**
 * Only the Lucide icons the code references by name (generated by
 * scripts/docs/collect-icons.mjs; `npm run docs:check` fails when it is stale).
 * Registering the full set (~1,700 icons) cost ~1.2 MB in the initial bundle.
 * The Icons page registers the full set on its own lazy route.
 */
export const appConfig: ApplicationConfig = {
  providers: [
    provideBrowserGlobalErrorListeners(),
    provideHkTheme('daisyui-v5'),
    providePipes(),
    provideRouter(
      routes,
      withComponentInputBinding(),
      withInMemoryScrolling({ scrollPositionRestoration: 'enabled', anchorScrolling: 'enabled' }),
    ),
    provideDocsPlatform(),
    provideToast(),
    provideAlert(),
    provideNotification({ position: 'top-right', maxStack: 5, pauseOnHover: true }),
    provideFormState({ mode: 'localStorage' }),
    provideLucideConfig({ size: 20, strokeWidth: 1.75 }),
    provideLucideIcons(...USED_LUCIDE_ICONS),
  ],
};
