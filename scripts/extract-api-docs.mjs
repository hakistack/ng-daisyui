#!/usr/bin/env node
/**
 * Generate the API manifest the docs platform reads.
 *
 * Every symbol exported from `projects/hakistack/ng-daisyui/src/public-api.ts`
 * is classified with the TypeScript type checker (see scripts/docs/api-extractor.mjs)
 * and written to `projects/shared-demos/platform/api/api-manifest.generated.ts`.
 *
 * The manifest is lazy-loaded by the docs app (API reference pages, per-page
 * API tabs, search), so its size does not affect the initial bundle.
 *
 *   npm run extract-api-docs          # regenerate
 *   npm run extract-api-docs -- --check   # fail if the committed file is stale (CI)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractPublicApi } from './docs/api-extractor.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_PATH = 'projects/shared-demos/platform/api/api-manifest.generated.ts';
const check = process.argv.includes('--check');

const { symbols } = extractPublicApi(ROOT);

const source = `// AUTO-GENERATED by scripts/extract-api-docs.mjs — DO NOT EDIT BY HAND.
// Source of truth: projects/hakistack/ng-daisyui/src/public-api.ts
// Re-run \`npm run extract-api-docs\` after changing the library's public API.
import type { ApiSymbol } from './api-manifest.types';

export type ApiSymbolName =
${symbols.map((s) => `  | '${s.name}'`).join('\n')};

export const API_SYMBOLS: readonly ApiSymbol[] = ${JSON.stringify(symbols, null, 1)};
`;

const outPath = resolve(ROOT, OUTPUT_PATH);
if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== source) {
    console.error(`✗ ${OUTPUT_PATH} is stale. Run \`npm run extract-api-docs\` and commit the result.`);
    process.exit(1);
  }
  console.log(`✓ ${OUTPUT_PATH} is up to date (${symbols.length} symbols).`);
  process.exit(0);
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, source);

const byKind = symbols.reduce((acc, s) => ((acc[s.kind] = (acc[s.kind] ?? 0) + 1), acc), {});
console.log(
  `✓ Extracted ${symbols.length} public symbols → ${OUTPUT_PATH}\n  ` +
    Object.entries(byKind)
      .sort((a, b) => b[1] - a[1])
      .map(([k, n]) => `${k}: ${n}`)
      .join(', '),
);
