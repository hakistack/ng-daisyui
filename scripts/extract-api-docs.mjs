#!/usr/bin/env node
/**
 * Generate the API manifests the docs platform reads, one per published package.
 *
 * Every symbol exported from a package's `src/public-api.ts` is classified with
 * the TypeScript type checker (see scripts/docs/api-extractor.mjs) and written to
 *   - projects/shared-demos/platform/api/api-manifest.generated.ts       (@hakistack/ng-daisyui)
 *   - projects/shared-demos/platform/api/api-manifest.i18n.generated.ts  (@hakistack/i18n)
 *
 * The manifests are lazy-loaded by the docs app (API reference pages, per-page
 * API tabs, search), so their size does not affect the initial bundle.
 *
 *   npm run extract-api-docs              # regenerate
 *   npm run extract-api-docs -- --check   # fail if a committed file is stale (CI)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractPublicApi } from './docs/api-extractor.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const MANIFESTS = [
  {
    pkg: 'ui',
    output: 'projects/shared-demos/platform/api/api-manifest.generated.ts',
    source: 'projects/hakistack/ng-daisyui/src/public-api.ts',
    label: "the library's",
    typeName: 'ApiSymbolName',
    constName: 'API_SYMBOLS',
  },
  {
    pkg: 'i18n',
    output: 'projects/shared-demos/platform/api/api-manifest.i18n.generated.ts',
    source: 'projects/hakistack/i18n/src/public-api.ts',
    label: '@hakistack/i18n',
    typeName: 'I18nApiSymbolName',
    constName: 'I18N_API_SYMBOLS',
  },
];

let failed = false;
for (const m of MANIFESTS) {
  const { symbols } = extractPublicApi(ROOT, m.pkg);
  const source = `// AUTO-GENERATED by scripts/extract-api-docs.mjs — DO NOT EDIT BY HAND.
// Source of truth: ${m.source}
// Re-run \`npm run extract-api-docs\` after changing ${m.label} public API.
import type { ApiSymbol } from './api-manifest.types';

export type ${m.typeName} =
${symbols.map((s) => `  | '${s.name}'`).join('\n')};

export const ${m.constName}: readonly ApiSymbol[] = ${JSON.stringify(symbols, null, 1)};
`;

  const outPath = resolve(ROOT, m.output);
  if (check) {
    const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
    if (current !== source) {
      console.error(`✗ ${m.output} is stale. Run \`npm run extract-api-docs\` and commit the result.`);
      failed = true;
    } else {
      console.log(`✓ ${m.output} is up to date (${symbols.length} symbols).`);
    }
    continue;
  }

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, source);
  const byKind = symbols.reduce((acc, s) => ((acc[s.kind] = (acc[s.kind] ?? 0) + 1), acc), {});
  console.log(
    `✓ Extracted ${symbols.length} public symbols → ${m.output}\n  ` +
      Object.entries(byKind)
        .sort((a, b) => b[1] - a[1])
        .map(([k, n]) => `${k}: ${n}`)
        .join(', '),
  );
}
if (failed) process.exit(1);
