#!/usr/bin/env node
/**
 * Collect the Lucide icons the demo/docs apps can render by name.
 *
 * `<svg [lucideIcon]="name">` resolves names through the icons registered with
 * `provideLucideIcons()`. Registering all ~1,700 icons put ~1.2 MB into the
 * initial bundle. Instead, every string literal in the demo, shared demos and
 * library source that equals a Lucide icon name is registered (a superset of
 * what can be rendered — no icon name is built by string concatenation; this
 * script fails if one ever is).
 *
 * The superset is deliberate: a literal that only looks like an icon name
 * (e.g. `'section'` in `Pick<X, 'section'>`) costs one icon's bytes, while a
 * missed name would render nothing. Rename such a literal only if the bytes matter.
 *
 *   node scripts/docs/collect-icons.mjs          # regenerate
 *   node scripts/docs/collect-icons.mjs --check  # CI: fail if stale
 */
import '@angular/compiler'; // @lucide/angular is partially compiled; needed to import it in Node.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUTPUTS = ['projects/demo/src/app/lucide-icons.generated.ts', 'projects/demo-v4/src/app/lucide-icons.generated.ts'];
const SOURCES = ['projects/demo/src', 'projects/demo-v4/src', 'projects/shared-demos', 'projects/hakistack/ng-daisyui/src'];
const check = process.argv.includes('--check');

const Lucide = await import('@lucide/angular');
/** kebab-case icon name → exported component class name */
const byName = new Map();
for (const [exportName, value] of Object.entries(Lucide)) {
  const icon = typeof value === 'function' ? value.icon : undefined;
  if (icon?.node && icon?.name && /^Lucide[A-Z]/.test(exportName) && !byName.has(icon.name)) byName.set(icon.name, exportName);
}

const files = SOURCES.flatMap((dir) => walk(resolve(ROOT, dir)));
const used = new Set();
const dynamic = [];
for (const file of files) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(/["'`]([a-z0-9]+(?:-[a-z0-9]+)*)["'`]/g)) if (byName.has(m[1])) used.add(m[1]);
  for (const m of src.matchAll(/\[lucideIcon\]="([^"]+)"/g)) {
    if (/\+|`|\$\{/.test(m[1])) dynamic.push(`${relative(ROOT, file)}: [lucideIcon]="${m[1]}"`);
  }
}
if (dynamic.length) {
  console.error('✗ Icon names built at runtime cannot be collected statically:\n  ' + dynamic.join('\n  '));
  process.exit(1);
}

const sorted = [...used].sort();
const classes = sorted.map((n) => byName.get(n));
const source = `// AUTO-GENERATED by scripts/docs/collect-icons.mjs — DO NOT EDIT BY HAND.
// Every Lucide icon name referenced as a string literal in the demo, shared demos and library source.
import {
${classes.map((c) => `  ${c},`).join('\n')}
} from '@lucide/angular';

export const USED_LUCIDE_ICONS = [
${classes.map((c) => `  ${c},`).join('\n')}
];
`;

let stale = false;
for (const out of OUTPUTS) {
  const abs = resolve(ROOT, out);
  if (!existsSync(dirname(abs))) continue;
  if (check) {
    if (!existsSync(abs) || readFileSync(abs, 'utf8') !== source) {
      console.error(`✗ ${out} is stale — run \`node scripts/docs/collect-icons.mjs\`.`);
      stale = true;
    }
  } else writeFileSync(abs, source);
}
if (stale) process.exit(1);
console.log(`✓ ${sorted.length} of ${byName.size} Lucide icons referenced${check ? ' (up to date)' : ` → ${OUTPUTS.join(', ')}`}`);

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry === 'dist' || entry.startsWith('.')) continue;
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|html)$/.test(entry) && !/\.spec\.ts$|\.generated\.ts$/.test(entry)) out.push(p);
  }
  return out;
}
